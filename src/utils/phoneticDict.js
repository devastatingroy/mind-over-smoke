/**
 * Clean a word token (strip trailing punctuation like commas, periods, quotes)
 */
export function cleanWord(rawWord) {
  if (!rawWord) return '';
  return rawWord.replace(/^[^a-zA-Z]+|[^a-zA-Z]+$/g, '').toLowerCase();
}

/**
 * Look up a word in the dictionary
 */
export function lookupWord(rawWord) {
  const cleaned = cleanWord(rawWord);
  if (!cleaned) return null;
  
  if (phoneticDict[cleaned]) {
    return {
      word: cleaned,
      ...phoneticDict[cleaned]
    };
  }

  // Fallback for simple plurals or common endings
  if (cleaned.endsWith('s') && phoneticDict[cleaned.slice(0, -1)]) {
    return {
      word: cleaned,
      ...phoneticDict[cleaned.slice(0, -1)]
    };
  }

  return {
    word: cleaned,
    phonetic: null,
    pos: '',
    def: '点击发音可朗读该单词'
  };
}

/**
 * Speak word using browser native speech synthesis
 */
export function speakWord(word) {
  if (typeof window === 'undefined' || !window.speechSynthesis) return;
  try {
    window.speechSynthesis.cancel(); // Stop any pending
    const utterance = new SpeechSynthesisUtterance(word);
    utterance.lang = 'en-US';
    utterance.rate = 0.9; // Slightly slower for crisp clear listening
    window.speechSynthesis.speak(utterance);
  } catch (err) {
    console.error('Speech error', err);
  }
}
